import { beforeAll, describe, expect, it } from 'vitest';
import request from 'supertest';
import type { Express } from 'express';

let app: Express;
beforeAll(async () => { process.env.APP_MODE = 'demo'; process.env.NODE_ENV = 'test'; ({ app } = await import('../server/index.js')); });

describe('demo coaching workflow', () => {
  it('protects data and supports coach to client training flow', async () => {
    expect((await request(app).get('/api/clients')).status).toBe(401);
    const coach = request.agent(app); const client = request.agent(app);
    expect((await coach.post('/api/auth/demo-login').send({ role: 'COACH' })).status).toBe(200);
    expect((await client.post('/api/auth/demo-login').send({ role: 'CLIENT' })).status).toBe(200);
    const startingDashboard = await client.get('/api/dashboard');
    expect(startingDashboard.body.sessions).toBeGreaterThanOrEqual(78);
    expect(startingDashboard.body.recentGuided[0]).toMatchObject({ exerciseCount: 3 });
    expect(startingDashboard.body.programs).toBe(1);
    expect(startingDashboard.body.currentProgram.name).toBe('Strength foundations');
    expect(startingDashboard.body.sessionsThisWeek).toBeGreaterThanOrEqual(0);
    expect(startingDashboard.body).not.toHaveProperty('clients');
    const coachDashboard = await coach.get('/api/dashboard');
    expect(coachDashboard.body.clients).toBe(2);
    expect(coachDashboard.body.assignedPrograms).toBe(2);
    expect(coachDashboard.body.activity).toHaveLength(14);
    expect(coachDashboard.body.sessionsThisWeek).toBeGreaterThanOrEqual(0);
    expect(coachDashboard.body.sessionsThisWeek).toBeLessThanOrEqual(coachDashboard.body.activity.reduce((total: number, day: { sessions: number }) => total + day.sessions, 0));
    expect(coachDashboard.body.recentSessions).toHaveLength(5);
    expect(coachDashboard.body.recentSessions[0].clientName).toBe('Sam Rivera');
    expect(coachDashboard.body.recentSessions[1].clientName).toBe('Jordan Lee');
    expect(coachDashboard.body.recentSessions[0].performedOn).toBe(coachDashboard.body.recentSessions[1].performedOn);
    expect(coachDashboard.body.recentSessions[0].logs).toHaveLength(1);
    const samHistory = await coach.get('/api/logs?clientId=demo-client&page=1&pageSize=8');
    expect(samHistory.status).toBe(200);
    expect(samHistory.body.totalSessions).toBe(20);
    expect(samHistory.body.items).toHaveLength(8);
    const jordanHistory = await coach.get('/api/logs?clientId=demo-client-2&page=1&pageSize=8');
    expect(jordanHistory.body.totalSessions).toBe(20);
    expect(jordanHistory.body.items).toHaveLength(8);
    const mixedHistory = await coach.get('/api/progress-history?clientId=demo-client&page=1&pageSize=8');
    expect(mixedHistory.status).toBe(200);
    expect(mixedHistory.body.totalEntries).toBe(78);
    expect(mixedHistory.body.items).toHaveLength(8);
    expect(mixedHistory.body.items.filter((item: { kind: string }) => item.kind === 'GUIDED')).toHaveLength(6);
    expect(mixedHistory.body.items.filter((item: { kind: string }) => item.kind === 'INDIVIDUAL')).toHaveLength(2);
    expect(mixedHistory.body.items.every((item: { date: string }) => /^\d{4}-\d{2}-\d{2}$/.test(item.date))).toBe(true);
    const benchHistory = await client.get('/api/logs?exerciseCode=BARBELL_BENCH_PRESS');
    expect(benchHistory.body.length).toBeGreaterThan(1);
    expect(benchHistory.body[0].weightKg).toBeGreaterThan(benchHistory.body.at(-1).weightKg);
    expect((await request(app).get('/api/goals')).status).toBe(401);
    expect((await coach.get('/api/goals')).body.map((goal: { code: string }) => goal.code)).toEqual(['HYPERTROPHY', 'STRENGTH', 'ENDURANCE', 'WEIGHT_LOSS']);
    const clients = await coach.get('/api/clients'); expect(clients.status).toBe(200); expect(clients.body.length).toBeGreaterThan(0);
    expect((await coach.put('/api/clients/demo-client').send({ name: 'Sam Rivera', goal: 'STRENGTH', notes: 'Coach private note' })).status).toBe(200);
    expect((await client.get('/api/me')).body.notes).toBeNull();
    expect((await client.put('/api/me').send({ name: 'Sam Rivera', goal: 'STRENGTH', weightUnit: 'LB' })).body.weightUnit).toBe('LB');
    expect((await client.get('/api/me')).body.weightUnit).toBe('LB');
    expect((await coach.get('/api/me')).body.weightUnit).toBe('KG');
    expect((await client.put('/api/me').send({ name: 'Sam Rivera', goal: 'STRENGTH', weightUnit: 'STONE' })).status).toBe(400);
    expect((await coach.get('/api/clients')).body.find((u: { id: string }) => u.id === 'demo-client').notes).toBe('Coach private note');
    expect((await client.get('/api/clients')).status).toBe(403);
    expect((await request(app).get('/api/exercises/BARBELL_BENCH_PRESS/image')).status).toBe(401);
    expect((await coach.get('/api/exercises/BARBELL_BENCH_PRESS/image')).status).toBe(404);
    const created = await coach.post('/api/programs').send({ name: 'Test strength plan', level: 'BEGINNER', goal: 'STRENGTH', days: [{ label: 'Full body', criteria: { exercisesCount: 2, autoPrescription: true } }] });
    expect(created.status).toBe(201); expect(created.body.content.days[0].exercises.length).toBe(2);
    const advanced = await coach.post('/api/programs').send({ name: 'Advanced criteria', days: [{ label: 'Chest', criteria: { muscles: ['CHEST'], categories: ['FREE_WEIGHT'], types: ['POLYARTICULAR'], sessionDurationMinutes: 45, autoPrescription: false, requiredExercises: ['BARBELL_BENCH_PRESS'], excludedExercises: ['SQUAT'], exercisePrescriptions: [{ exercise: 'BARBELL_BENCH_PRESS', nbSets: { min: 3, max: 5 }, nbReps: { value: 8 }, restSeconds: { value: 90 }, weight: { value: 40 } }] } }] });
    expect(advanced.status).toBe(201);
    expect(advanced.body.content.days[0].exercises).toHaveLength(1);
    expect(advanced.body.content.days[0].exercises[0].nbSets).toEqual({ min: 3, max: 5 });
    expect(advanced.body.content.days[0].exercises[0].weight).toEqual({ value: 40 });
    const programId = created.body.id;
    expect((await client.get(`/api/programs/${programId}/exercises/0/0/embed`)).status).toBe(404);
    expect((await coach.get(`/api/programs/${programId}/exercises/0/9/embed`)).status).toBe(404);
    expect((await coach.get(`/api/programs/${programId}/exercises/0/0/embed`)).body.error).toContain('demo mode');
    const adjusted = await coach.patch(`/api/programs/${programId}/exercise`).send({ dayIndex: 0, exerciseIndex: 0, sets: 5, reps: 6, restSeconds: 120 });
    expect(adjusted.status).toBe(200); expect(adjusted.body.content.days[0].exercises[0].nbSets.value).toBe(5);
    expect(adjusted.body.content.days[0].exercises[1].nbSets.value).toBe(4);
    expect((await client.patch(`/api/programs/${programId}/exercise`).send({ dayIndex: 0, exerciseIndex: 1, sets: 7, reps: 7, restSeconds: 60 })).status).toBe(403);
    expect((await client.get('/api/programs')).body.some((p: { id: string }) => p.id === programId)).toBe(false);
    expect((await coach.post(`/api/programs/${programId}/assign`).send({ clientId: 'demo-client' })).status).toBe(200);
    expect((await client.get('/api/programs')).body.some((p: { id: string }) => p.id === programId)).toBe(true);
    const exercise = created.body.content.days[0].exercises[0];
    expect((await client.post('/api/logs').send({ programId, exerciseCode: exercise.code, exerciseName: exercise.name, sets: 3, reps: 8, weightKg: 40 })).status).toBe(201);
    const backdated = await client.post('/api/logs').send({ programId, exerciseCode: exercise.code, sets: 3, reps: 8, weightKg: 42.5, performedOn: '2025-04-10' });
    expect(backdated.status).toBe(201);
    expect(backdated.body.performedOn.slice(0, 10)).toBe('2025-04-10');
    expect(backdated.body.performedAt.slice(0, 10)).toBe('2025-04-10');
    expect((await client.post('/api/logs').send({ programId, exerciseCode: exercise.code, sets: 3, reps: 8, performedOn: '2025-02-30' })).status).toBe(400);
    expect((await client.post('/api/logs').send({ programId, exerciseCode: exercise.code, sets: 3, reps: 8, performedOn: '2100-01-01' })).status).toBe(400);
    expect((await coach.get('/api/logs?clientId=demo-client')).body.some((log: { programId: string }) => log.programId === programId)).toBe(false);
    expect((await coach.get('/api/progress-history?clientId=demo-client')).body.totalEntries).toBe(78);
    expect((await client.get('/api/progress-history?clientId=demo-client-2')).status).toBe(403);
    expect((await coach.get('/api/progress-history?clientId=not-my-client')).status).toBe(404);
    expect((await coach.get('/api/progress-history?clientId=demo-client&page=0')).status).toBe(400);
    const firstPage = await coach.get('/api/logs?clientId=demo-client&page=1&pageSize=1');
    const secondPage = await coach.get('/api/logs?clientId=demo-client&page=2&pageSize=1');
    expect(firstPage.status).toBe(200);
    expect(firstPage.body.totalSessions).toBeGreaterThan(1);
    expect(firstPage.body.items.length).toBeGreaterThan(0);
    expect(new Set(firstPage.body.items.map((log: { performedOn?: string; performedAt: string }) => (log.performedOn || log.performedAt).slice(0, 10))).size).toBe(1);
    expect((secondPage.body.items[0].performedOn || secondPage.body.items[0].performedAt).slice(0, 10)).not.toBe((firstPage.body.items[0].performedOn || firstPage.body.items[0].performedAt).slice(0, 10));
    expect((await coach.get('/api/logs?clientId=demo-client&page=0')).status).toBe(400);
    expect((await client.get('/api/logs?clientId=demo-client-2&page=1')).status).toBe(403);
    expect((await coach.get('/api/logs?clientId=not-my-client')).status).toBe(404);
    const exerciseLogs = await coach.get(`/api/logs?clientId=demo-client&exerciseCode=${encodeURIComponent(exercise.code)}`);
    expect(exerciseLogs.status).toBe(200);
    expect(exerciseLogs.body.every((log: { exerciseCode: string }) => log.exerciseCode === exercise.code)).toBe(true);
    expect((await client.get(`/api/logs?clientId=demo-client-2&exerciseCode=${encodeURIComponent(exercise.code)}`)).status).toBe(403);
    expect((await coach.get(`/api/logs?clientId=demo-client-2&exerciseCode=${encodeURIComponent(exercise.code)}`)).status).toBe(200);
    expect((await coach.get('/api/logs?clientId=demo-client&exerciseCode[]=SQUAT')).status).toBe(400);
    expect((await client.post('/api/messages').send({ recipientId: 'demo-client-2', body: 'No access' })).status).toBe(403);
    expect((await coach.post('/api/messages').send({ recipientId: 'demo-client', body: 'Well done' })).status).toBe(201);
    expect((await client.get('/api/messages?peerId=demo-coach')).body.some((m: { body: string }) => m.body === 'Well done')).toBe(true);
    expect((await client.post('/api/messages/read').send({ peerId: 'demo-client-2' })).status).toBe(403);
    expect((await client.post('/api/messages/read').send({ peerId: 'demo-coach' })).status).toBe(200);
    expect((await client.get('/api/messages?peerId=demo-coach')).body.find((m: { body: string }) => m.body === 'Well done').readAt).toBeTruthy();
    const preferences = await client.put('/api/me').send({ name: 'Sam Rivera', goal: 'STRENGTH', notifyMessages: false, notifyPrograms: false });
    expect(preferences.status).toBe(200);
    expect(preferences.body).toMatchObject({ emailLocale: 'en', notifyMessages: false, notifyPrograms: false });
    expect((await client.patch('/api/me/language').send({ locale: 'fr' })).status).toBe(400);
    expect((await client.patch('/api/me/language').send({ locale: 'en' })).body.emailLocale).toBe('en');
  });
});
