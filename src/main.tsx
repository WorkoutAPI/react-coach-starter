import React from 'react';
import { createRoot } from 'react-dom/client';
import { App } from './App';
import { brand } from './config/brand';
import { applyTheme } from './config/theme';
import i18n from './i18n';
import './index.css';
document.title = `${brand.name} — ${brand.description}`;
document.documentElement.lang = i18n.resolvedLanguage || brand.languages[0];
i18n.on('languageChanged', language => { document.documentElement.lang = language; });
const fontLink = document.createElement('link');
fontLink.rel = 'stylesheet';
fontLink.href = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(brand.theme.fontDisplay).replace(/%20/g, '+')}:wght@400;500;600;700&family=${encodeURIComponent(brand.theme.fontSans).replace(/%20/g, '+')}:wght@400;500;600;700&display=swap`;
document.head.append(fontLink);
const root = document.documentElement;
root.style.setProperty('--font-sans', brand.theme.fontSans);
root.style.setProperty('--font-display', brand.theme.fontDisplay);
applyTheme(localStorage.getItem('coach-theme') === 'dark');
createRoot(document.getElementById('root')!).render(<React.StrictMode><App/></React.StrictMode>);
